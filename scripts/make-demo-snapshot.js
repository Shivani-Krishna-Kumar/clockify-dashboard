// Bundles a read-only copy of the dashboard database into demo-data/snapshot.js for a hosted demo
// (Vercel). The source database is opened read-only, so a running server is not disturbed.
//
//   npm run snapshot                      (uses data/dashboard.db, or DB_PATH)
//
// The snapshot contains REAL employee names, emails, hours and entry descriptions. It is listed in
// .gitignore on purpose: do not commit it to a public repository.
const fs = require("fs");
const os = require("os");
const path = require("path");
const { DatabaseSync } = require("node:sqlite");
const cfg = require("../src/config");

const out = path.join(cfg.root, "demo-data", "snapshot.js");
const tmp = path.join(os.tmpdir(), `clockify-snapshot-${process.pid}.db`);
fs.rmSync(tmp, { force: true });

if (!fs.existsSync(cfg.dbPath)) throw new Error(`No database at ${cfg.dbPath}. Run the dashboard and sync first.`);
const src = new DatabaseSync(cfg.dbPath, { readOnly: true });
src.exec(`VACUUM INTO '${tmp.replace(/\\/g, "/").replace(/'/g, "''")}'`);

const one = (sql) => src.prepare(sql).get();
const meta = {
  tz: cfg.tz,
  lastDay: one("SELECT MAX(work_date) AS d FROM entries").d,
  firstDay: one("SELECT MIN(work_date) AS d FROM entries").d,
  users: one("SELECT COUNT(*) AS n FROM users").n,
  entries: one("SELECT COUNT(*) AS n FROM entries").n,
  createdAt: new Date().toISOString(),
};
src.close();

const db = fs.readFileSync(tmp).toString("base64");
fs.rmSync(tmp, { force: true });
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `// Generated by scripts/make-demo-snapshot.js. Contains real data - do not commit publicly.\nmodule.exports = ${JSON.stringify({ ...meta, db })};\n`);

console.log(`Wrote ${path.relative(cfg.root, out)} (${(fs.statSync(out).size / 1024).toFixed(0)} KB)`);
console.log(`  ${meta.users} users, ${meta.entries} entries, ${meta.firstDay} to ${meta.lastDay}, timezone ${meta.tz}`);
console.log("  Demo 'today' will be frozen at", meta.lastDay);
